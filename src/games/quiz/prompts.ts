const BY_ID = new Map(QUIZ_PROMPTS.map((prompt) => [prompt.id, prompt]))

export function findQuizPrompt(id: unknown): QuizPrompt | undefined {
  return typeof id === 'string' ? BY_ID.get(id) : undefined
}

/**
 * 자기 답을 저장할 모양으로 정리한다. 형식이 맞지 않으면 null.
 * 4지선다 → 보기 번호(0~3), OX → 0(X) | 1(O), 숫자 → 범위 안의 정수.
 */
export function normalizeQuizAnswer(prompt: QuizPrompt, raw: unknown): number | null {
  const value = typeof raw === 'boolean' ? Number(raw) : Number(raw)
  if (raw === null || raw === undefined || raw === '' || !Number.isInteger(value)) return null
  if (prompt.type === 'choice') return value >= 0 && value <= 3 ? value : null
  if (prompt.type === 'ox') return value === 0 || value === 1 ? value : null
  return value >= prompt.min && value <= prompt.max ? value : null
}

/** 답을 사람이 읽을 말로 */
export function quizAnswerLabel(prompt: QuizPrompt, value: number): string {
  if (prompt.type === 'choice') return prompt.options[value] ?? '?'
  if (prompt.type === 'ox') return value === 1 ? 'O' : 'X'
  return `${value}${prompt.unit}`
}

